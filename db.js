/* 用户标注（localStorage）读写 */
const TAG_KEY = 'packAgent.refTags';

/* 某些环境（file:// 打开、隐私模式）可能禁用 localStorage，这里做内存兜底，保证标注功能不失效 */
let memTags = {};
function safeStore() {
  try {
    return typeof localStorage !== 'undefined' ? localStorage : null;
  } catch (e) {
    return null;
  }
}

function loadRefTags() {
  const s = safeStore();
  if (s) {
    try {
      return JSON.parse(s.getItem(TAG_KEY) || '{}') || {};
    } catch (e) {}
  }
  return memTags;
}

function saveRefTag(id, system, tags) {
  const all = loadRefTags();
  all[id] = { system, tags: tags || [], at: new Date().toISOString() };
  memTags = all;
  const s = safeStore();
  if (s) {
    try {
      s.setItem(TAG_KEY, JSON.stringify(all));
    } catch (e) {}
  }
  return all;
}

/* 应用标注：给参考素材打上体系归属与标签 */
function applyRefTags() {
  const tags = loadRefTags();
  ALL_ITEMS.forEach((it) => {
    if (it.zone !== 'reference') return;
    const t = tags[it.id];
    if (t && t.system && t.system !== 'skip') {
      it.pending = false;
      it.system = t.system;
      it.tags = t.tags && t.tags.length ? t.tags : [t.system === 'guofeng' ? '国风' : '现代'];
    } else {
      it.pending = true;
      it.system = null;
      it.skipped = !!(t && t.system === 'skip');
      it.tags = it.skipped ? ['已跳过'] : ['待标注'];
    }
  });
}

